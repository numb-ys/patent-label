"""Generate a pre-Unicode AutoCAD fork without changing the 2026 sources."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def prepare(year=2014):
    if year not in (2014, 2019):
        raise ValueError("Supported legacy targets: 2014, 2019")
    target = ROOT / f"src/PatentLabel.UI{year}"
    target.mkdir(parents=True, exist_ok=True)
    s = (ROOT / "src/PatentLabel.UI/Interaction.cs").read_text(encoding="utf-8")
    s = s.replace("using System.Text.Json;", "using System;\nusing System.Collections.Generic;\nusing System.Linq;\nusing System.Web.Script.Serialization;")
    s = s.replace("PatentLabel.UI", f"PatentLabel.UI{year}")
    s = s.replace('"0.4.0"', f'"0.4.0-{year}"')
    s = s.replace("JsonSerializer.Serialize", "LegacyJson.Serialize")
    s = s.replace('"PatentLabel.lsp"', f'"PatentLabel{year}.lsp"')
    s = s.replace('    public static bool IdentifierValid(ResultBuffer arguments) =>\n        arguments.AsArray() is [var value] && value.Value is string text && LabelIdentifier.IsIdentifier(text);',
                  '''    public static bool IdentifierValid(ResultBuffer arguments)
    {
        var values = arguments.AsArray();
        return values.Length == 1 && values[0].Value is string text && LabelIdentifier.IsIdentifier(text);
    }''')
    s = s.replace("internal static class PreviewArguments", "internal sealed class PreviewArguments")
    s = s.replace("    internal static (Point3d Target, string Number, double Height, double Landing, double Gap)\n        Read(ResultBuffer arguments)",
                  "    internal static PreviewArguments Read(ResultBuffer arguments)")
    s = s.replace("double.IsFinite(", "LegacyNumbers.IsFinite(")
    s = s.replace("        return (target, number, height, landing, gap);", "        return new PreviewArguments(target, number, height, landing, gap);")
    marker = "internal sealed class PreviewArguments\n{"
    s = s.replace(marker, marker + '''
    private readonly Point3d target;
    private readonly string number;
    private readonly double height, landing, gap;

    private PreviewArguments(Point3d target, string number, double height, double landing, double gap)
    {
        this.target = target; this.number = number;
        this.height = height; this.landing = landing; this.gap = gap;
    }

    internal void Deconstruct(out Point3d target, out string number, out double height,
                              out double landing, out double gap)
    {
        target = this.target; number = this.number;
        height = this.height; landing = this.landing; gap = this.gap;
    }
''')
    s += '''
internal static class LegacyJson
{
    internal static string Serialize(object value) => new JavaScriptSerializer().Serialize(value);
}

internal static class LegacyNumbers
{
    internal static bool IsFinite(double value) => !double.IsNaN(value) && !double.IsInfinity(value);
}
'''
    (target / "Interaction.cs").write_text("// Generated by scripts/legacy/prepare-sources.py.\n" + s, encoding="utf-8")
    fonts = (ROOT / "src/PatentLabel.UI/LabelFonts.cs").read_text(encoding="utf-8")
    fonts = "using System;\nusing System.IO;\n" + fonts.replace("PatentLabel.UI", f"PatentLabel.UI{year}")
    (target / "LabelFonts.cs").write_text("// Generated by scripts/legacy/prepare-sources.py.\n" + fonts, encoding="utf-8")
    attachment = (ROOT / "src/PatentLabel.UI/LabelAttachment.cs").read_text(encoding="utf-8")
    (target / "LabelAttachment.cs").write_text("// Generated by scripts/legacy/prepare-sources.py.\n" +
                                             attachment.replace("PatentLabel.UI", f"PatentLabel.UI{year}"), encoding="utf-8")
    grip = (ROOT / "src/PatentLabel.UI/LabelGripEditing.cs").read_text(encoding="utf-8")
    grip = grip.replace("PatentLabel.UI", f"PatentLabel.UI{year}").replace("System.Text.Json.JsonSerializer.Serialize", "LegacyJson.Serialize")
    (target / "LabelGripEditing.cs").write_text("// Generated by scripts/legacy/prepare-sources.py.\n" + grip, encoding="utf-8")
    backend = (ROOT / "src/PatentLabel.lsp").read_text(encoding="utf-8")
    backend = backend.replace("0.4.0", f"0.4.0-{year}")
    backend = backend.replace(";;; UTF-8. AutoCAD 2021+ with LISPSYS=1/2; verified host recorded in README.",
                              f";;; AutoCAD {year}: CP936/GBK source, no UTF-8 BOM or LISPSYS dependency.")
    backend = backend.replace("PatentLabel.UI.dll", f"PatentLabel.UI{year}.dll")
    # Keep Chinese prompts on Chinese Windows 2014 and avoid Unicode-only arrows.
    backend = backend.replace("→", "->")
    backend = backend.replace('(bh:sync-ui)\n(prompt "\\n专利附图标号', '''(defun c:BHVER ()
  (prompt (strcat "\\nPatentLabel 0.4.0-2014 | CAD " (getvar "ACADVER")))
  (prompt (if (bh:ui-available-p) "\\n2014 预览模块：已加载。" "\\n2014 预览模块：未加载，当前为基础模式。"))
  (prompt (strcat "\\n黑体文件：" (if (findfile "simhei.ttf") (findfile "simhei.ttf") "未找到")))
  (princ))

(bh:sync-ui)
(prompt "\\n专利附图标号'''.replace("2014", str(year)))
    destination = ROOT / f"legacy/AutoCAD{year}/PatentLabel{year}.lsp"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(backend.replace("\n", "\r\n").encode("gbk"))
    print(destination)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--year", type=int, choices=(2014, 2019), default=2014)
    prepare(parser.parse_args().year)
